def build_verified_json():
    print("Building verified 2024 Spring Subject A (80 Questions) dataset...")
    output_data = []

    for spec in VERIFIED_QUESTIONS_SPECS:
        q_num = spec[0]
        cat = spec[1]
        title = spec[2]
        body = spec[3]
        choices_raw = spec[4]
        explanation = spec[5]

        official_sym = OFFICIAL_ANSWERS_2024_SPRING[q_num]

        # Validation: Check for duplicate choice texts
        seen_texts = set()
        choices_list = []
        for sym, text in choices_raw:
            if text in seen_texts:
                print(f"[WARNING] Duplicate choice text detected in Q{q_num}: {text}")
            seen_texts.add(text)

            is_corr = (sym == official_sym)
            choices_list.append({
                "symbol": sym,
                "text": text,
                "isCorrect": is_corr
            })

        q_item = {
            "year": 2024,
            "season": "SPRING",
            "examType": "SUBJECT_A",
            "questionNum": q_num,
            "category": cat,
            "title": title,
            "bodyText": body,
            "explanation": explanation,
            "imageUrls": [f"/questions/2024_spring_subject_a_q{q_num}.png"],
            "choices": choices_list,
            "modelAnswers": []
        }
        output_data.append(q_item)

    verified_file = os.path.join(DATA_DIR, 'verified_2024_spring.json')
    full_file = os.path.join(DATA_DIR, 'questions_full.json')

    with open(verified_file, 'w', encoding='utf-8') as f:
        json.dump(output_data, f, ensure_ascii=False, indent=2)

    with open(full_file, 'w', encoding='utf-8') as f:
        json.dump(output_data, f, ensure_ascii=False, indent=2)

    print(f"[Success] Saved {len(output_data)} verified questions to {verified_file} and {full_file}")

if __name__ == "__main__":
    build_verified_json()
